/**
 * Экранирует строку для безопасной вставки внутрь одинарных кавычек shell:
 * закрывает кавычку, вставляет экранированную `'` и открывает снова ('\''),
 * так любая строка становится одним литералом без интерпретации метасимволов.
 */
export function shellQuote(s: string): string {
  return `'${s.replace(/'/g, "'\\''")}'`;
}
